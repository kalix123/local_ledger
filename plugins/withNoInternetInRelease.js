/**
 * Local Ledger never goes online, so release builds don't request the INTERNET permission.
 *
 * It can't simply be blocked in app.json: development builds load the JavaScript bundle from
 * the Metro dev server over the network and would stop working. Instead this adds a
 * release-only manifest (android/app/src/release/AndroidManifest.xml). Android's manifest
 * merger gives build-type manifests priority, so `tools:node="remove"` there strips INTERNET
 * (including any copy declared by a library) from release APKs only.
 */
const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('expo/config-plugins');

const RELEASE_MANIFEST = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withNoInternetInRelease.js. Do not edit; change the plugin instead. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android" xmlns:tools="http://schemas.android.com/tools">
  <uses-permission android:name="android.permission.INTERNET" tools:node="remove" />
</manifest>
`;

module.exports = function withNoInternetInRelease(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'release');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'AndroidManifest.xml'), RELEASE_MANIFEST);
      return cfg;
    },
  ]);
};
